    console.log("🔍 Первый проход начался...");
    const firstPass = await client.chat.completions.create({
      model: "deepseek-chat",
      messages: [
        { role: "system", content: FIRST_PASS_PROMPT },
        { role: "user", content: userContent },
      ],
      temperature: 0.2,
    });

    const firstResult =
      firstPass.choices[0]?.message?.content || "Ошибка первого прохода";
    console.log("✅ Первый проход завершён.");

