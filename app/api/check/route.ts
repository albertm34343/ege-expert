// ПОДСЧЁТ СЛОВ ПО ПРАВИЛАМ ФИПИ-2026
// • слова через дефис = 1 слово
// • инициалы + фамилия (М.Ю. Лермонтов) = 1 слово
// • цифры не учитываются
// =====================================================================
function countWordsFipi(text: string): number {
  // 1) Склеиваем инициалы с фамилией: "М.Ю. Лермонтов" → "М.Ю.Лермонтов"
  let normalized = text.replace(
    /\b([А-ЯЁA-Z]\.\s*){1,3}\s*([А-ЯЁA-Z][а-яёa-z]+)/g,
    (m) => m.replace(/\s+/g, "")
  );

  // 2) Разбиваем по пробелам
  const tokens = normalized.trim().split(/\s+/).filter(Boolean);

  // 3) Отфильтровываем чистые числа и пунктуацию
  const words = tokens.filter((tok) => {
    const clean = tok.replace(/[«»"'(),.!?;:—–\-]/g, "");
    if (!clean) return false;
    if (/^\d+$/.test(clean)) return false; // чистые числа
    return /[А-Яа-яЁёA-Za-z]/.test(clean); // должна быть буква
  });

  return words.length;
}

